// Turns the server's theme folders into plain data for clients that can't use
// CSS. Run with --check in CI to fail when themes.json is out of date.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
// The themes belong to the server: a clone of it beside this one, or say where with WMS_THEMES.
const themesDir = process.env.WMS_THEMES || join(here, '..', '..', '..', 'WittyMediaServer', 'themes')
if (!existsSync(themesDir)) {
  console.error(`no themes at ${themesDir}: clone WittyMediaServer beside this repository, or set WMS_THEMES`)
  process.exit(1)
}
const outFile = join(here, '..', 'data', 'themes.json')

// The CSS variables a native client needs, with the name it uses for them.
const WANTED = {
  '--bg': 'background', '--bg-2': 'panel', '--bg-3': 'card', '--bg-4': 'border',
  '--fg': 'text', '--fg-2': 'textSecondary', '--fg-3': 'textHint',
  '--accent': 'accent', '--accent-fg': 'onAccent', '--accent-text': 'accentText',
  '--danger': 'danger', '--ok': 'ok',
}
const HEX = /^#[0-9a-fA-F]{6}$/
const SHORT_HEX = /^#[0-9a-fA-F]{3}$/

// #abc is #aabbcc, and is what a theme's author may well have written.
const longHex = (value) => (SHORT_HEX.test(value) ? `#${[...value.slice(1)].map((c) => c + c).join('')}` : value)

function colours(css, inherited) {
  const out = { ...inherited }
  // A declaration in a comment isn't one, and a note can mention a variable and a value.
  const live = css.replace(/\/\*[\s\S]*?\*\//g, '')
  for (const [, name, written] of live.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
    const key = WANTED[name]
    const value = longHex(written.trim())
    if (key && HEX.test(value)) out[key] = value.toLowerCase()
  }
  return out
}

// Worked out by the server and written into each theme.json (its internal/themes/design.go), not into theme.css:
// the focus ring, the scrim behind a sheet, words over a picture, and how solid the page-colour scrim behind a
// hero's words is (docs/UI-PLATFORMS.md in the server; its PR 444 made every hero draw with it).
const DERIVED = { focus: 'focus', scrim: 'scrim', onImage: 'onImage', borderStrong: 'borderStrong', accentHover: 'accentHover', controlLine: 'controlLine' }
const HEX8 = /^#[0-9a-fA-F]{8}$/

function derived(meta, id) {
  const out = {}
  for (const [from, key] of Object.entries(DERIVED)) {
    const value = longHex(String(meta.colors?.[from] ?? ''))
    if (!HEX.test(value) && !HEX8.test(value)) throw new Error(`theme ${id}: colors.${from} is not a colour`)
    out[key] = value.toLowerCase()
  }
  const heroScrim = meta.tv?.heroScrim
  if (typeof heroScrim !== 'number' || heroScrim <= 0 || heroScrim > 1) throw new Error(`theme ${id}: no tv.heroScrim`)
  return { colours: out, heroScrim }
}

const read = (id) => readFileSync(join(themesDir, id, 'theme.css'), 'utf8')
const base = colours(read('default'), {})
const themes = readdirSync(themesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(themesDir, d.name, 'theme.json')))
  .map((d) => {
    const meta = JSON.parse(readFileSync(join(themesDir, d.name, 'theme.json'), 'utf8'))
    const more = derived(meta, meta.id)
    return { id: meta.id, name: meta.name, scheme: meta.scheme, heroScrim: more.heroScrim, colours: { ...colours(read(d.name), base), ...more.colours } }
  })
  .sort((a, b) => a.id.localeCompare(b.id))

for (const t of themes) {
  for (const key of Object.values(WANTED)) {
    if (!t.colours[key]) throw new Error(`theme ${t.id}: no value for ${key}`)
  }
}

const text = JSON.stringify({ defaultTheme: 'default', themes }, null, 2) + '\n'

// The connect screen opens before any server's theme can apply, so it wears the default theme: these are its
// colours under the server's own names, written here so the page never keeps a copy of its own.
const cssFile = join(here, '..', 'connect', 'theme.css')
const rgba = (hex, alpha) => `rgba(${[1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(', ')}, ${alpha})`
function connectCss(theme) {
  const c = theme.colours
  const vars = {
    '--bg': c.background, '--bg-2': c.panel, '--bg-3': c.card, '--bg-4': c.border,
    '--fg': c.text, '--fg-2': c.textSecondary, '--fg-3': c.textHint,
    '--accent': c.accent, '--accent-2': c.accentHover, '--accent-fg': c.onAccent, '--accent-text': c.accentText,
    '--danger': c.danger, '--ok': c.ok, '--control-line': c.controlLine,
    // The glow at the top of the page is the accent at 16%, and so is danger's tint.
    '--glow': rgba(c.accent, '.16'), '--danger-tint': rgba(c.danger, '.16'),
  }
  return [
    '/* SPDX-License-Identifier: GPL-3.0-or-later */',
    '/* Copyright (C) 2026 WittyWilla and contributors */',
    `/* Generated by shared/scripts/build-themes.mjs from the server's ${theme.name} theme. Do not edit. */`,
    ':root {',
    ...Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`),
    '}',
    '',
  ].join('\n')
}
const css = connectCss(themes.find((t) => t.id === 'default'))

const same = (file, want) => existsSync(file) && readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === want
if (process.argv.includes('--check')) {
  if (!same(outFile, text) || !same(cssFile, css)) {
    console.error('shared/data/themes.json or shared/connect/theme.css is out of date: run node shared/scripts/build-themes.mjs')
    process.exit(1)
  }
} else {
  writeFileSync(outFile, text)
  writeFileSync(cssFile, css)
  console.log(`wrote ${themes.length} themes and the connect screen's colours`)
}
