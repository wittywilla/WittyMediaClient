"""Writes the server's design tokens as constants for the apps:

  apple/WittyKit/Sources/WittyKit/DesignTokens.generated.swift
  android/app/src/main/kotlin/com/wittywilla/wittymediaclient/ui/DesignTokens.generated.kt

The single source is the server's themes/tokens.json (itself generated from its CSS; docs/plans/DESIGN-2.md,
section 2, is the schema). Never edit the results by hand.

  python3 scripts/gen-design-tokens.py                 write both
  python3 scripts/gen-design-tokens.py --check         fail if either is out of date
  python3 scripts/gen-design-tokens.py --tokens FILE   read this tokens.json

Where tokens.json is found: --tokens, $WITTY_TOKENS, then the server checkout beside this repository
(../WittyMediaServer/themes/tokens.json). With none of them both modes fail.

Strict: the file must have every section the contract names (no defaults, no fallbacks for older servers); keys the
contract doesn't name are left out.
"""
import json, os, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SWIFT = ROOT / 'apple/WittyKit/Sources/WittyKit/DesignTokens.generated.swift'
KOTLIN = ROOT / 'android/app/src/main/kotlin/com/wittywilla/wittymediaclient/ui/DesignTokens.generated.kt'
HEADER = 'Generated by scripts/gen-design-tokens.py from the server\'s themes/tokens.json. Do not edit; see docs/plans/DESIGN-2.md.'

# Only these sections are written, and in this order: what the apps read. Others in the file (colours, depth,
# card, tenFoot ...) are the web's and the theme engine's, not constants an app needs.
SECTIONS = ['type', 'space', 'elevation', 'focus', 'input', 'nav', 'tv', 'layout', 'density', 'motion']
# Also read from the file though the contract keeps their names: shape roles and the card sizes of the 1x devices.
EXTRA = {'control': ['height', 'heightTouch', 'minTarget'], 'card': ['width', 'wideWidth'], 'tenFoot': ['textScale', 'focus', 'minGutter', 'minTarget']}


def load(path):
    """The sections the apps read, exactly as the server's file has them. No defaults and no fallbacks: a file without a
    section the contract names (DESIGN-2.md section 2) is refused, so a client is never built against a half schema."""
    data = json.loads(path.read_text())
    missing = [s for s in SECTIONS + list(EXTRA) if s not in data]
    if missing:
        raise SystemExit(f'{path}: missing sections {missing}; this needs the Design 2 tokens.json')
    out = {s: data[s] for s in SECTIONS}
    for s, keys in EXTRA.items():
        out[s] = {k: data[s][k] for k in keys if k in data[s]}
    out['version'] = data['version']
    return out


def ident(name):
    name = re.sub(r'[^0-9A-Za-z_]', '_', name)
    return ('n' + name) if name[0].isdigit() else name


def kind(v):
    """'num' | 'str' | 'bool' | 'nums' | 'strs' | 'table' (dict of dicts of lists) | 'dict'."""
    if v is None: return 'str'
    if isinstance(v, bool): return 'bool'
    if isinstance(v, (int, float)): return 'num'
    if isinstance(v, str): return 'str'
    if isinstance(v, list):
        if v and all(isinstance(x, dict) for x in v): return 'dicts'
        if not v: return 'nums'
        if all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in v): return 'nums'
        if all(isinstance(x, str) for x in v): return 'strs'
        raise SystemExit(f'mixed list: {v}')
    if isinstance(v, dict):
        if v and all(isinstance(x, list) for x in v.values()): return 'map'
        return 'dict'
    raise SystemExit(f'unsupported: {v!r}')


def num(v):
    return repr(float(v)) if not float(v).is_integer() else f'{int(v)}.0'


# ---------- Swift ----------
SWIFT_WORDS = {'default', 'in', 'is', 'static', 'return', 'case', 'let', 'var', 'func', 'for', 'if', 'else', 'switch', 'where', 'self', 'true', 'false', 'internal', 'public', 'private', 'enum', 'struct', 'class', 'init', 'type', 'subscript', 'operator'}


def sname(n):
    n = ident(n)
    return f'`{n}`' if n in SWIFT_WORDS else n


def swift_val(v):
    k = kind(v)
    if v is None: return 'String', '"none"'
    if k == 'dicts': return '[[String: Double]]', '[' + ', '.join('[' + ', '.join(f'{json.dumps(a)}: {num(b)}' for a, b in x.items()) + ']' for x in v) + ']'
    if k == 'num': return 'Double', num(v)
    if k == 'bool': return 'Bool', 'true' if v else 'false'
    if k == 'str': return 'String', json.dumps(v)
    if k == 'nums': return '[Double]', '[' + ', '.join(num(x) for x in v) + ']'
    if k == 'strs': return '[String]', '[' + ', '.join(json.dumps(x) for x in v) + ']'
    if k == 'map':
        numeric = all(kind(b) == 'nums' for b in v.values())
        item = (lambda x: num(x)) if numeric else (lambda x: json.dumps(x))
        return ('[String: [Double]]' if numeric else '[String: [String]]'), '[' + ', '.join(f'{json.dumps(a)}: [' + ', '.join(item(x) for x in b) + ']' for a, b in v.items()) + ']'
    raise SystemExit('dict')


def typename(name):
    if name == 'type': return 'Typography'
    return ident(name[0].upper() + name[1:]) if not name[0].isdigit() else 'N' + name


def swift_enum(name, d, indent):
    pad = '    ' * indent
    lines = [f'{pad}public enum {typename(name)} {{']
    for k, v in d.items():
        if kind(v) == 'dict':
            lines += swift_enum(k, v, indent + 1)
        else:
            t, lit = swift_val(v)
            if k == 'shadow': t = '[[String: Double]]'
            lines.append(f'{pad}    public static let {sname(k)}: {t} = {lit}')
    lines.append(f'{pad}}}')
    return lines


def to_swift(t):
    out = ['// SPDX-License-Identifier: GPL-3.0-or-later', '// Copyright (C) 2026 WittyWilla and contributors',
           f'// {HEADER}', '', 'import Foundation', '',
           '/// The design tokens of the server (themes/tokens.json) as constants: sizes in points (1 TV unit is 1 pt on Apple TV),',
           '/// times in milliseconds, tracking in em. Missing keys in the server\'s file are the contract\'s defaults.',
           'public enum DesignTokens {',
           f'    public static let version: Double = {num(t["version"])}']
    for s in SECTIONS + list(EXTRA):
        if s in t:
            out += swift_enum(s, t[s], 1)
    out.append('}')
    return '\n'.join(out) + '\n'


# ---------- Kotlin ----------
KOTLIN_WORDS = {'in', 'is', 'object', 'val', 'var', 'fun', 'when', 'class', 'return', 'true', 'false', 'null', 'this', 'super', 'typeof', 'as', 'if', 'else', 'for', 'while', 'do', 'try', 'package', 'interface', 'typealias'}


def kname(n):
    n = ident(n)
    return f'`{n}`' if n in KOTLIN_WORDS else n


def kot_val(v):
    k = kind(v)
    if v is None: return '"none"'
    if k == 'dicts': return 'listOf(' + ', '.join('mapOf(' + ', '.join(f'{json.dumps(a)} to {num(b)}' for a, b in x.items()) + ')' for x in v) + ')'
    if k == 'num': return f'{num(v)}'
    if k == 'bool': return 'true' if v else 'false'
    if k == 'str': return json.dumps(v)
    if k == 'nums': return 'listOf(' + ', '.join(num(x) for x in v) + ')'
    if k == 'strs': return 'listOf(' + ', '.join(json.dumps(x) for x in v) + ')'
    if k == 'map': return 'mapOf(' + ', '.join(f'{json.dumps(a)} to listOf(' + ', '.join(json.dumps(x) for x in b) + ')' for a, b in v.items()) + ')'
    raise SystemExit('dict')


def kot_obj(name, d, indent):
    pad = '    ' * indent
    lines = [f'{pad}object {typename(name)} {{']
    for k, v in d.items():
        if kind(v) == 'dict':
            lines += kot_obj(k, v, indent + 1)
        elif kind(v) in ('num', 'bool', 'str'):
            lines.append(f'{pad}    const val {kname(k)} = {kot_val(v)}')
        elif k_empty(v):
            lines.append(f'{pad}    val {kname(k)}: List<Map<String, Double>> = emptyList()')
        else:
            lines.append(f'{pad}    val {kname(k)} = {kot_val(v)}')
    lines.append(f'{pad}}}')
    return lines


def k_empty(v):
    return isinstance(v, list) and not v


def to_kotlin(t):
    out = ['// SPDX-License-Identifier: GPL-3.0-or-later', '// Copyright (C) 2026 WittyWilla and contributors',
           f'// {HEADER}', '', 'package com.wittywilla.wittymediaclient.ui', '',
           '/** The design tokens of the server (themes/tokens.json): sizes in dp (a TV unit is 0.5 dp), times in milliseconds. */',
           'object DesignTokens {', f'    const val version = {num(t["version"])}']
    for s in SECTIONS + list(EXTRA):
        if s in t:
            out += kot_obj(s, t[s], 1)
    out.append('}')
    return '\n'.join(out) + '\n'


def find_tokens(argv):
    if '--tokens' in argv:
        return pathlib.Path(argv[argv.index('--tokens') + 1])
    if os.environ.get('WITTY_TOKENS'):
        return pathlib.Path(os.environ['WITTY_TOKENS'])
    for guess in (ROOT.parent / 'WittyMediaServer/themes/tokens.json', ROOT.parent.parent / 'WittyMediaServer/themes/tokens.json',
                  ROOT.parent / 'design-WittyMediaServer/themes/tokens.json'):
        if guess.exists():
            return guess
    return None


def main(argv):
    check = '--check' in argv
    source = find_tokens(argv)
    if source is None:
        print('gen-design-tokens: tokens.json not found; pass --tokens FILE', file=sys.stderr)
        return 1
    tokens = load(source)
    results = [(SWIFT, to_swift(tokens)), (KOTLIN, to_kotlin(tokens))]
    stale = []
    for path, text in results:
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print('out of date, run scripts/gen-design-tokens.py: ' + ', '.join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
