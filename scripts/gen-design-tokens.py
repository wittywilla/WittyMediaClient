"""Writes the server's design tokens as constants for the apps:

  apple/WittyKit/Sources/WittyKit/DesignTokens.generated.swift
  android/app/src/main/kotlin/com/wittywilla/wittymediaclient/ui/DesignTokens.generated.kt

The single source is the server's themes/tokens.json (itself generated from its CSS; docs/plans/DESIGN-2.md,
section 2, is the schema). Never edit the results by hand.

  python3 scripts/gen-design-tokens.py                 write both
  python3 scripts/gen-design-tokens.py --check         fail if either is out of date
  python3 scripts/gen-design-tokens.py --tokens FILE   read this tokens.json

Where tokens.json is found: --tokens, $WITTY_TOKENS, then the server checkout beside this repository
(../WittyMediaServer/themes/tokens.json). With none of them, --check says so and passes (a lone checkout of this
repository in CI), and writing fails.

Tolerant by design, so an app built against an older or a newer server file still builds: every value the contract
names has a default (the numbers in DESIGN-2.md) that the file overrides, and keys the contract doesn't name are
left out.
"""
